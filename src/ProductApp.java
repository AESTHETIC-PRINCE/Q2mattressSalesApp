private void processSale() {
    String name = txtName.getText().trim();
    String product = (String) cmbProduct.getSelectedItem();
    double price;
    try {
        price = Double.parseDouble(txtPrice.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.",
                "Invalid Input", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (name.isEmpty() || price < 0) {
        JOptionPane.showMessageDialog(this, "Please enter a customer name and a valid price.",
                "Invalid Input", JOptionPane.ERROR_MESSAGE);
        return;
    }

    IProductCalculations calc = new ProductCalculations(price);
    double vat = calc.GetVat();
    double commission = calc.GetCommission();
    double total = calc.GetTotal();

    JOptionPane.showMessageDialog(this,
            "Customer Name: " + name + "\n" +
            "Product: " + product + "\n" +
            "VAT: R " + vat + "\n" +
            "COMMISSION: R " + commission + "\n" +
            "TOTAL: R " + total);

    try (PrintWriter out = new PrintWriter(new FileWriter("data.txt"))) {
        out.println("DATA LOG");
        out.println("****************************************");
        out.println("Customer Name: " + name);
        out.println("Product: " + product);
        out.println("VAT: R " + vat);
        out.println("COMMISSION: R " + commission);
        out.println("TOTAL: R " + total);
        out.println("****************************************");
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Could not save to data.txt: " + ex.getMessage());
    }
}

